

## attention neural networks provide mechanisms for modeling non-locality
## they do this by predicting the regions of a vector that are relevant

## A quasi-linearized and regularized version of this could be potentially useful for modeling non-linearity of exposures.
## This suggests a general idea for how to represent this, under the idea that attention should be locally-monotone, but globally non-local
## in other words, attention is paid to larger blobs or lines that may be spatially separated, but not highly disparate pixel patterns


## The general idea, functional process on covariate representation of attention.
## the set of features for a specific location as a set of covariates, as well as the spatial processes of the covariates
## the attention process corresponding to a specific point can be represented as the karhunenen-loeve expansion of some candidate process
## the loadings on the process would depend then on bivariate functions of the spatial process as well as individual points.

## simplest representation, consider a tensor-product b-spline basis representation over space.
## positively constrained coefficients of this b-spline basis representation could then be given by functions of both covariates and spatial process covariates

